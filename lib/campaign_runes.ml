let base_by_id id =
  List.find (fun (r : base_rune) -> r.id = id) base_runes

let modifier_by_id id =
  List.find (fun (r : modifier_rune) -> r.id = id) modifier_runes

let power_by_id id =
  List.find (fun (r : power_rune) -> r.id = id) power_runes

(* The forged item's name and icon for a (base, modifier) pair - the
   power does not change the name, only the ability. *)
let forged_name_of (base : string) (modifier : string) :
    forged_name option =
  List.find_opt
    (fun (n : forged_name) -> n.base = base && n.modifier = modifier)
    forged_names

(* Any rune by id, with the two fields every claim gate reads. *)
type rune_kind =
  | Base_rune of base_rune
  | Modifier_rune of modifier_rune
  | Power_rune of power_rune

let rune_id = function
  | Base_rune r -> r.id
  | Modifier_rune r -> r.id
  | Power_rune r -> r.id

let rune_guard = function
  | Base_rune r -> r.guard
  | Modifier_rune r -> r.guard
  | Power_rune r -> r.guard

let rune_location = function
  | Base_rune r -> r.location
  | Modifier_rune r -> r.location
  | Power_rune r -> r.location

let rune_by_id (id : string) : rune_kind option =
  List.find_opt
    (fun k -> rune_id k = id)
    ((List.map (fun r -> Base_rune r) base_runes)
     @ (List.map (fun r -> Modifier_rune r) modifier_runes)
     @ (List.map (fun r -> Power_rune r) power_runes))
