#!/usr/bin/env python3
"""
Extract the rune tables: Assets/Runes/Runes.xml into lib/campaign_runes.ml.

The rune system is three parallel registries plus a name table:
  Base (15)     - the forged slot (position) and the base ability (data);
                  JXXX's OnQuerySkill/OnGiveDamage switch on [code].
  Modifier (10) - the forge arithmetic: data_add/data_mult edit the base
                  ability, power_add/power_mult the power, per the runes'
                  own descriptions ("Adds +2 to Base Rune ability and +50%
                  to Power Rune ability").
  Power (13)    - the item's effect; JXXX switches on [code], POWERDATA is
                  [data].
  BaseModifier  - the forged item's name and icon for a (base, modifier)
                  pair; 15 x 10 = 150 rows.

JXXX.lua is the shared script every forged item runs - its hooks read the
current rune's code/data through GET_CURRENT_RUNE_* - so this extractor
carries data only, the same split as companions.
"""

import xml.etree.ElementTree as ET
from pathlib import Path
import sys

BASE = Path("game/Assets/Assets/Runes")
SRC = BASE / "Runes.xml"


def fnum(s: str) -> str:
    """Render an XML float attribute the way OCaml wants it: 1 -> 1.0."""
    v = float(s)
    return repr(v) if v != int(v) else f"{int(v)}.0"


def ocaml_string(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def parse() -> dict:
    root = ET.parse(SRC).getroot()

    def common(el) -> dict:
        return {
            "id": el.get("id", ""),
            "name_text": el.get("name", ""),
            "desc_text": el.get("description", ""),
            "code": el.get("code", ""),
            "guard": el.get("guard", ""),
            "level": int(el.get("level", "0") or 0),
            "location": el.get("location", ""),
            "diff_add": int(el.get("diff_add", "0") or 0),
            "diff_mult": fnum(el.get("diff_mult", "1") or "1"),
        }

    bases = []
    for el in root.findall("Base"):
        b = common(el)
        b["data"] = int(el.get("data", "0") or 0)
        b["position"] = el.get("position", "")
        bases.append(b)

    modifiers = []
    for el in root.findall("Modifier"):
        m = common(el)
        m["data_add"] = int(el.get("data_add", "0") or 0)
        m["data_mult"] = fnum(el.get("data_mult", "1") or "1")
        m["power_add"] = int(el.get("power_add", "0") or 0)
        m["power_mult"] = fnum(el.get("power_mult", "1") or "1")
        modifiers.append(m)

    powers = []
    for el in root.findall("Power"):
        p = common(el)
        p["data"] = int(el.get("data", "0") or 0)
        p["text"] = el.get("text", "")
        powers.append(p)

    names = [
        {
            "base": el.get("base", ""),
            "modifier": el.get("modifier", ""),
            "name_text": el.get("name", ""),
            "icon": int(el.get("icon", "0") or 0),
        }
        for el in root.findall("BaseModifier")
    ]
    return {"bases": bases, "modifiers": modifiers, "powers": powers, "names": names}


def render(d: dict) -> str:
    L = []
    L.append("(* Generated by tools/extract_runes.py - do not edit *)")
    L.append("")
    L.append("(* The three rune registries plus the (base, modifier) name table,")
    L.append("   straight out of Assets/Runes/Runes.xml. Every forged item runs the")
    L.append("   shared JXXX script, which reads these codes and data values through")
    L.append("   GET_CURRENT_RUNE_* - [code] is its switch key, [data] the number the")
    L.append("   BASEDATA/POWERDATA natives return before the modifier edits them. *)")
    L.append("")
    L.append("type base_rune = {")
    for f in ("id", "name_text", "desc_text", "code", "guard", "location", "position"):
        L.append(f"  {f}: string;")
    L.append("  level: int;")
    L.append("  diff_add: int;")
    L.append("  diff_mult: float;")
    L.append("  data: int;")
    L.append("}")
    L.append("")
    L.append("type modifier_rune = {")
    for f in ("id", "name_text", "desc_text", "code", "guard", "location"):
        L.append(f"  {f}: string;")
    L.append("  level: int;")
    L.append("  diff_add: int;")
    L.append("  diff_mult: float;")
    L.append("  data_add: int;")
    L.append("  data_mult: float;")
    L.append("  power_add: int;")
    L.append("  power_mult: float;")
    L.append("}")
    L.append("")
    L.append("type power_rune = {")
    for f in ("id", "name_text", "desc_text", "code", "guard", "location", "text"):
        L.append(f"  {f}: string;")
    L.append("  level: int;")
    L.append("  diff_add: int;")
    L.append("  diff_mult: float;")
    L.append("  data: int;")
    L.append("}")
    L.append("")
    L.append("type forged_name = {")
    for f in ("base", "modifier", "name_text"):
        L.append(f"  {f}: string;")
    L.append("  icon: int;")
    L.append("}")
    L.append("")
    L.append("let base_runes : base_rune list = [")
    for b in d["bases"]:
        L.append("  {")
        L.append(f"    id = {ocaml_string(b['id'])};")
        L.append(f"    name_text = {ocaml_string(b['name_text'])};")
        L.append(f"    desc_text = {ocaml_string(b['desc_text'])};")
        L.append(f"    code = {ocaml_string(b['code'])};")
        L.append(f"    guard = {ocaml_string(b['guard'])};")
        L.append(f"    location = {ocaml_string(b['location'])};")
        L.append(f"    position = {ocaml_string(b['position'])};")
        L.append(f"    level = {b['level']};")
        L.append(f"    diff_add = {b['diff_add']};")
        L.append(f"    diff_mult = {b['diff_mult']};")
        L.append(f"    data = {b['data']};")
        L.append("  };")
    L.append("]")
    L.append("")
    L.append("let modifier_runes : modifier_rune list = [")
    for m in d["modifiers"]:
        L.append("  {")
        L.append(f"    id = {ocaml_string(m['id'])};")
        L.append(f"    name_text = {ocaml_string(m['name_text'])};")
        L.append(f"    desc_text = {ocaml_string(m['desc_text'])};")
        L.append(f"    code = {ocaml_string(m['code'])};")
        L.append(f"    guard = {ocaml_string(m['guard'])};")
        L.append(f"    location = {ocaml_string(m['location'])};")
        L.append(f"    level = {m['level']};")
        L.append(f"    diff_add = {m['diff_add']};")
        L.append(f"    diff_mult = {m['diff_mult']};")
        L.append(f"    data_add = {m['data_add']};")
        L.append(f"    data_mult = {m['data_mult']};")
        L.append(f"    power_add = {m['power_add']};")
        L.append(f"    power_mult = {m['power_mult']};")
        L.append("  };")
    L.append("]")
    L.append("")
    L.append("let power_runes : power_rune list = [")
    for p in d["powers"]:
        L.append("  {")
        L.append(f"    id = {ocaml_string(p['id'])};")
        L.append(f"    name_text = {ocaml_string(p['name_text'])};")
        L.append(f"    desc_text = {ocaml_string(p['desc_text'])};")
        L.append(f"    code = {ocaml_string(p['code'])};")
        L.append(f"    guard = {ocaml_string(p['guard'])};")
        L.append(f"    location = {ocaml_string(p['location'])};")
        L.append(f"    text = {ocaml_string(p['text'])};")
        L.append(f"    level = {p['level']};")
        L.append(f"    diff_add = {p['diff_add']};")
        L.append(f"    diff_mult = {p['diff_mult']};")
        L.append(f"    data = {p['data']};")
        L.append("  };")
    L.append("]")
    L.append("")
    L.append("let forged_names : forged_name list = [")
    for n in d["names"]:
        L.append("  {")
        L.append(f"    base = {ocaml_string(n['base'])};")
        L.append(f"    modifier = {ocaml_string(n['modifier'])};")
        L.append(f"    name_text = {ocaml_string(n['name_text'])};")
        L.append(f"    icon = {n['icon']};")
        L.append("  };")
    L.append("]")
    L.append("")
    L.append("let base_by_id id =")
    L.append("  List.find (fun (r : base_rune) -> r.id = id) base_runes")
    L.append("")
    L.append("let modifier_by_id id =")
    L.append("  List.find (fun (r : modifier_rune) -> r.id = id) modifier_runes")
    L.append("")
    L.append("let power_by_id id =")
    L.append("  List.find (fun (r : power_rune) -> r.id = id) power_runes")
    L.append("")
    L.append("(* The forged item's name and icon for a (base, modifier) pair - the")
    L.append("   power does not change the name, only the ability. *)")
    L.append("let forged_name_of (base : string) (modifier : string) :")
    L.append("    forged_name option =")
    L.append("  List.find_opt")
    L.append("    (fun (n : forged_name) -> n.base = base && n.modifier = modifier)")
    L.append("    forged_names")
    L.append("")
    L.append("(* Any rune by id, with the two fields every claim gate reads. *)")
    L.append("type rune_kind =")
    L.append("  | Base_rune of base_rune")
    L.append("  | Modifier_rune of modifier_rune")
    L.append("  | Power_rune of power_rune")
    L.append("")
    L.append("let rune_id = function")
    L.append("  | Base_rune r -> r.id")
    L.append("  | Modifier_rune r -> r.id")
    L.append("  | Power_rune r -> r.id")
    L.append("")
    L.append("let rune_guard = function")
    L.append("  | Base_rune r -> r.guard")
    L.append("  | Modifier_rune r -> r.guard")
    L.append("  | Power_rune r -> r.guard")
    L.append("")
    L.append("let rune_location = function")
    L.append("  | Base_rune r -> r.location")
    L.append("  | Modifier_rune r -> r.location")
    L.append("  | Power_rune r -> r.location")
    L.append("")
    L.append("let rune_by_id (id : string) : rune_kind option =")
    L.append("  List.find_opt")
    L.append("    (fun k -> rune_id k = id)")
    L.append("    ((List.map (fun r -> Base_rune r) base_runes)")
    L.append("     @ (List.map (fun r -> Modifier_rune r) modifier_runes)")
    L.append("     @ (List.map (fun r -> Power_rune r) power_runes))")
    L.append("")
    return "\n".join(L)


def main() -> None:
    import argparse
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--output", default="lib/campaign_runes.ml")
    args = parser.parse_args()

    d = parse()
    print(f"Base: {len(d['bases'])}  Modifier: {len(d['modifiers'])}  "
          f"Power: {len(d['powers'])}  BaseModifier: {len(d['names'])}")
    generated = render(d)
    if args.check:
        current = Path(args.output).read_text(encoding="utf-8")
        if current != generated:
            print(f"{args.output} is stale - rerun without --check", file=sys.stderr)
            sys.exit(1)
        print(f"{args.output} is up to date")
        return
    Path(args.output).write_text(generated, encoding="utf-8", newline="\n")
    print(f"wrote {args.output}")


if __name__ == "__main__":
    main()
